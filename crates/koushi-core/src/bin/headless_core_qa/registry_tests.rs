#[test]
fn parse_env_flag_accepts_only_explicit_boolean_values() {
    for (value, expected) in [
        ("1", true),
        ("true", true),
        ("TRUE", true),
        ("0", false),
        ("false", false),
        ("FALSE", false),
        ("", false),
    ] {
        assert_eq!(parse_env_flag("QA_FLAG", value), Ok(expected));
    }

    assert!(parse_env_flag("QA_FLAG", "yes").is_err());
}

